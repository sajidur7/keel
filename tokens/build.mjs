// Keel token build.
// Reads tokens.json and writes:
//   tokens.css           — raw CSS variables, dark (default) + light themes
//   theme.css            — Tailwind v4 @theme block mapping those variables to utilities
//   figma-variables.json — collections/modes/variables, imported into Figma as native Variables
//   tokens.studio.json   — the same tokens in Tokens Studio format (dark/light sets)
//
// Run: npm run tokens

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const t = JSON.parse(readFileSync(join(here, "tokens.json"), "utf8"));
const HEADER = "/* Generated by tokens/build.mjs from tokens.json. Do not edit by hand. */\n";

// ---------- helpers ----------
const themeVars = (mode) => {
  const out = [];
  for (const [k, v] of Object.entries(t.color[mode])) out.push([`--${k}`, v]);
  for (const [tone, set] of Object.entries(t.tag[mode]))
    for (const [part, v] of Object.entries(set)) out.push([`--tag-${tone}-${part}`, v]);
  for (const [k, v] of Object.entries(t.shadow[mode])) out.push([`--elevation-${k}`, v]);
  return out;
};
const block = (sel, vars, extra = "") =>
  `${sel} {\n${extra}${vars.map(([k, v]) => `  ${k}: ${v};`).join("\n")}\n}\n`;
const key = (k) => String(k).replace(".", "_");

// ---------- tokens.css ----------
const staticVars = [
  ["--font-sans", t.font.family.sans],
  ["--font-mono", t.font.family.mono],
  ...Object.entries(t.font.size).map(([k, v]) => [`--text-${k}`, v]),
  ...Object.entries(t.radius).map(([k, v]) => [`--radius-${k}`, v]),
  ...Object.entries(t.border).map(([k, v]) => [`--border-${k}`, v]),
  ...Object.entries(t.size).map(([k, v]) => [`--size-${k}`, v]),
  ...Object.entries(t.motion.duration).map(([k, v]) => [`--duration-${k}`, v]),
  ...Object.entries(t.motion.ease).map(([k, v]) => [`--ease-${k}`, v]),
  ...Object.entries(t.z).map(([k, v]) => [`--z-${k}`, v]),
];

let css = HEADER;
css += block(":root", staticVars);
css += "\n/* Dark is the default theme. */\n";
css += block(':root,\n[data-theme="dark"]', themeVars("dark"), "  color-scheme: dark;\n");
css += "\n";
css += block('[data-theme="light"]', themeVars("light"), "  color-scheme: light;\n");
css += `
/* Reduced motion: every duration collapses to near-instant. */
@media (prefers-reduced-motion: reduce) {
  :root {
    --duration-instant: 0ms;
    --duration-fast: 0ms;
    --duration-base: 0ms;
    --duration-slow: 0ms;
  }
}
`;
writeFileSync(join(here, "tokens.css"), css);

// ---------- theme.css (Tailwind v4) ----------
const colorNames = Object.keys(t.color.dark);
const tones = Object.keys(t.tag.dark);
let theme = HEADER + `/*
  Import after tailwindcss:
    @import "tailwindcss";
    @import "../tokens/tokens.css";
    @import "../tokens/theme.css";
  Tailwind's default palette is switched off, so only Keel colors exist as utilities
  (bg-card, text-subtle, border-line-strong, bg-tag-blue-bg ...).
*/

@custom-variant dark (&:where(:root:not([data-theme="light"]) *, [data-theme="dark"] *));
@custom-variant light (&:where([data-theme="light"], [data-theme="light"] *));

@theme inline {
  --color-*: initial;
  --color-transparent: transparent;
  --color-current: currentColor;
  --color-white: #ffffff;
  --color-black: #000000;
${colorNames.map((c) => `  --color-${c}: var(--${c});`).join("\n")}
${tones.flatMap((tn) => ["bg", "border", "text"].map((p) => `  --color-tag-${tn}-${p}: var(--tag-${tn}-${p});`)).join("\n")}

  --shadow-*: initial;
${Object.keys(t.shadow.dark).map((k) => `  --shadow-${k}: var(--elevation-${k});`).join("\n")}
}

@theme {
  --font-sans: ${t.font.family.sans};
  --font-mono: ${t.font.family.mono};

${Object.entries(t.font.size).map(([k, v]) => `  --text-${k}: ${v};`).join("\n")}
  --text-eyebrow--letter-spacing: ${t.font.tracking.eyebrow};
  --text-eyebrow--line-height: 1;
  --text-stat--letter-spacing: ${t.font.tracking.stat};
  --text-stat--line-height: 1;
  --text-display--letter-spacing: ${t.font.tracking.page};
  --text-display--line-height: ${t.font.leading.tight};
  --text-page--letter-spacing: ${t.font.tracking.page};
  --text-page--line-height: ${t.font.leading.tight};
  --text-title--line-height: ${t.font.leading.tight};
  --text-body--line-height: ${t.font.leading.snug};
  --text-small--line-height: ${t.font.leading.snug};
  --text-caption--line-height: ${t.font.leading.snug};

  --radius-*: initial;
${Object.entries(t.radius).map(([k, v]) => `  --radius-${k}: ${v};`).join("\n")}

${Object.entries(t.motion.ease).map(([k, v]) => `  --ease-${k}: ${v};`).join("\n")}

  --breakpoint-*: initial;
${Object.entries(t.breakpoint).filter(([k]) => k !== "xs").map(([k, v]) => `  --breakpoint-${k}: ${v};`).join("\n")}
}

/* Body styles stay outside @layer on purpose: an embedding page (CMS, preview frame, hosted artifact)
   often ships plain body { color; font } rules, and unlayered rules always beat layered ones. */
body {
  background: var(--background);
  color: var(--foreground);
  font-family: var(--font-sans);
  font-size: var(--text-body);
  line-height: ${t.font.leading.snug};
  font-feature-settings: "ss01", "cv11";
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

@layer base {
  * { border-color: var(--border); }
  html { -webkit-text-size-adjust: 100%; }
  ::selection { background: color-mix(in srgb, var(--foreground) 22%, transparent); }
  :focus { outline: none; }
  * { scrollbar-width: thin; scrollbar-color: var(--line-strong) transparent; }
}

/* Keel utilities */
@utility eyebrow {
  font-size: var(--text-eyebrow);
  line-height: 1;
  letter-spacing: ${t.font.tracking.eyebrow};
  text-transform: uppercase;
  font-weight: ${t.font.weight.medium};
  color: var(--faint);
}
@utility tabular { font-variant-numeric: tabular-nums; }
@utility focus-ring {
  outline: none;
  &:focus-visible { box-shadow: var(--elevation-focus); }
}
@utility duration-fast { transition-duration: var(--duration-fast); }
@utility duration-base { transition-duration: var(--duration-base); }
@utility duration-slow { transition-duration: var(--duration-slow); }
`;
writeFileSync(join(here, "theme.css"), theme);

// ---------- figma-variables.json ----------
// Shape is consumed by the Figma import script (see /figma/README.md).
const toFigmaColor = (v) => v; // kept as CSS strings; the Figma script parses hex and rgba()
const figma = {
  collections: [
    {
      name: "Keel / Color",
      modes: ["Dark", "Light"],
      variables: [
        ...colorNames.map((c) => ({
          name: `color/${c}`,
          type: "COLOR",
          values: { Dark: toFigmaColor(t.color.dark[c]), Light: toFigmaColor(t.color.light[c]) },
        })),
        ...tones.flatMap((tn) =>
          ["bg", "border", "text"].map((p) => ({
            name: `tag/${tn}/${p}`,
            type: "COLOR",
            values: { Dark: t.tag.dark[tn][p], Light: t.tag.light[tn][p] },
          })),
        ),
      ],
    },
    {
      name: "Keel / Dimension",
      modes: ["Value"],
      variables: [
        ...Object.entries(t.space).map(([k, v]) => ({ name: `space/${key(k)}`, type: "FLOAT", values: { Value: parseFloat(v) } })),
        ...Object.entries(t.radius).map(([k, v]) => ({ name: `radius/${k}`, type: "FLOAT", values: { Value: parseFloat(v) } })),
        ...Object.entries(t.size).map(([k, v]) => ({ name: `size/${k}`, type: "FLOAT", values: { Value: parseFloat(v) } })),
        ...Object.entries(t.font.size).map(([k, v]) => ({ name: `font-size/${k}`, type: "FLOAT", values: { Value: parseFloat(v) } })),
        ...Object.entries(t.border).map(([k, v]) => ({ name: `border/${k}`, type: "FLOAT", values: { Value: parseFloat(v) } })),
      ],
    },
  ],
  textStyles: [
    { name: "Keel/Eyebrow", size: 11, weight: 500, lineHeight: 100, tracking: 8, upper: true },
    { name: "Keel/Caption", size: 12, weight: 400, lineHeight: 135 },
    { name: "Keel/Caption Medium", size: 12, weight: 500, lineHeight: 135 },
    { name: "Keel/Small", size: 13, weight: 400, lineHeight: 135 },
    { name: "Keel/Body", size: 14, weight: 400, lineHeight: 135 },
    { name: "Keel/Body Medium", size: 14, weight: 500, lineHeight: 135 },
    { name: "Keel/Title", size: 16, weight: 500, lineHeight: 120 },
    { name: "Keel/Page title", size: 18, weight: 600, lineHeight: 120, tracking: -1 },
    { name: "Keel/Display", size: 22, weight: 600, lineHeight: 120, tracking: -1 },
    { name: "Keel/Stat", size: 28, weight: 500, lineHeight: 100, tracking: -2 },
    { name: "Keel/Mono", size: 12, weight: 400, lineHeight: 135, mono: true },
  ],
};
writeFileSync(join(here, "figma-variables.json"), JSON.stringify(figma, null, 2) + "\n");

// ---------- tokens.studio.json ----------
const studio = { $themes: [], $metadata: { tokenSetOrder: ["core", "dark", "light"] } };
studio.core = {
  space: Object.fromEntries(Object.entries(t.space).map(([k, v]) => [key(k), { value: v, type: "spacing" }])),
  radius: Object.fromEntries(Object.entries(t.radius).map(([k, v]) => [k, { value: v, type: "borderRadius" }])),
  fontSize: Object.fromEntries(Object.entries(t.font.size).map(([k, v]) => [k, { value: v, type: "fontSizes" }])),
  fontFamily: { sans: { value: "Geist", type: "fontFamilies" }, mono: { value: "Geist Mono", type: "fontFamilies" } },
};
for (const mode of ["dark", "light"]) {
  studio[mode] = {
    color: Object.fromEntries(Object.entries(t.color[mode]).map(([k, v]) => [k, { value: v, type: "color" }])),
    tag: Object.fromEntries(
      Object.entries(t.tag[mode]).map(([tn, s]) => [tn, Object.fromEntries(Object.entries(s).map(([p, v]) => [p, { value: v, type: "color" }]))]),
    ),
  };
  studio.$themes.push({ name: mode[0].toUpperCase() + mode.slice(1), selectedTokenSets: { core: "source", [mode]: "enabled" } });
}
writeFileSync(join(here, "tokens.studio.json"), JSON.stringify(studio, null, 2) + "\n");

console.log("Keel tokens built: tokens.css, theme.css, figma-variables.json, tokens.studio.json");
